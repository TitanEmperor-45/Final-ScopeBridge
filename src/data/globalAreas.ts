export const ALL_GLOBAL_AREAS: GlobalAreaOption[] = GLOBAL_AREA_GROUPS.flatMap((g) => g.options);

export function findGlobalAreaMeta(areaName: string): GlobalAreaOption | undefined {
  const clean = (areaName || '').trim().toLowerCase();
  return ALL_GLOBAL_AREAS.find(
    (opt) =>
      opt.area.toLowerCase() === clean ||
      opt.area.toLowerCase().includes(clean) ||
      clean.includes(opt.city.toLowerCase())
  );
}
